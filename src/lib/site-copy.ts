export function getSiteCopyValue(
  copy: Readonly<Record<string, string>>,
  key: string,
): string | undefined {
  const value = copy[key]
  return typeof value === 'string' && value.trim() ? value : undefined
}

export function getMissingSiteCopyKeys(
  copy: Readonly<Record<string, string>>,
): string[] {
  return REQUIRED_SITE_COPY_KEYS.filter(
    key => !getSiteCopyValue(copy, key),
  )
}
